ROOT = Path(__file__).resolve().parents[1]
FOLDERS = ('in_motion', 'wiki', 'lattices', 'journal', 'crm', 'inbox_raw', 'raw')
MARKER = '<!-- second-brain-home: generated by tools/brain.py -->'


def metadata(text):
    """Read only top-level scalar fields; deliberately not a full YAML parser."""
    match = re.match(r'\A\ufeff?---\s*\n(.*?)\n---\s*(?:\n|$)', text, re.S)
    if not match:
        return {}, text
    fields = {}
    for line in match[1].splitlines():
        item = re.match(r'^([\w-]+):\s*(.*?)\s*$', line)
        if item:
            value = item[2]
            if value.startswith('"'):
                try:
                    value = json.loads(value)
                except ValueError:
                    value = value.strip('"')
            elif value.startswith("'") and value.endswith("'"):
                value = value[1:-1].replace("''", "'")
            else:
                value = value.split(' #', 1)[0].strip()
            if isinstance(value, str):
                fields[item[1]] = value
    return fields, text[match.end():]

def notes(root, include_private=False):
    result = []
    for folder in FOLDERS:
        for path in sorted((root / folder).rglob('*.md')):
            # Do not follow symlinks/junctions outside the intended vault.
            if not path.resolve().is_relative_to(root.resolve()):
                continue
            rel = path.relative_to(root).as_posix()
            if path.name.lower() in ('index.md', 'readme.md'):
                continue
            text = path.read_text(encoding='utf-8-sig')
            meta, body = metadata(text)
            if not include_private and ('private' in path.relative_to(root).parts or 'private' in path.resolve().relative_to(root.resolve()).parts or meta.get('domain') == 'private'):
                continue
            heading = re.search(r'^#\s+(.+)$', body, re.M)
            title = meta.get('title') or meta.get('name') or (heading[1] if heading else path.stem)
            result.append(dict(path=rel, title=title, meta=meta, body=body, text=text, mtime=path.stat().st_mtime))
    return result

def tasks(note):
    """Return unchecked source lines, ignoring frontmatter and fenced examples."""
    fence = None
    meta, body = metadata(note['text'])
    offset = len(note['text'].splitlines()) - len(body.splitlines())
    for number, line in enumerate(body.splitlines(), offset + 1):
        stripped = line.lstrip()
        match = re.match(r'^(`{3,}|~{3,})', stripped)
        if match:
            symbol = match[1]
            if fence is None:
                fence = symbol
            elif symbol[0] == fence[0] and len(symbol) >= len(fence):
                fence = None
            continue
        task = re.match(r'^\s*[-*+] \[ \]\s+(.+)', line)
        if task and fence is None:
            yield number, task[1]

def active(note):
    path = note['path']
    return (path.startswith('in_motion/') or (path.startswith('wiki/') and '/projects/' in path)) and note['meta'].get('status') == 'active'

def snapshot(root, include_private=False):
    items = notes(root, include_private)
    streams = [n for n in items if active(n)]
    pending = [(n, line, task) for n in streams for line, task in tasks(n)]
    inbox = [n for n in items if n['path'].startswith('inbox_raw/') and '/processed/' not in n['path']]
    return items, streams, pending, inbox

def search(root, query, include_private=False, limit=8):
    terms = set(re.findall(r'\w+', query.casefold()))
    if not terms:
        return []
    results = []
    for note in notes(root, include_private):
        folded = note['text'].casefold()
        if not all(term in folded for term in terms):
            continue
        score = sum(folded.count(term) + 5 * note['title'].casefold().count(term) for term in terms)
        lines = note['text'].splitlines()
        number = next((i for i, line in enumerate(lines, 1) if any(t in line.casefold() for t in terms)), 1)
        results.append(dict(path=note['path'], title=note['title'], line=number, excerpt=lines[number-1][:220], score=score))
    return sorted(results, key=lambda r: (-r['score'], r['path']))[:limit]

def capture(root, text, title=None):
    if not text.strip():
        raise ValueError('Catatan kosong. Isi teks atau gunakan --file.')
    title = (title or text.strip().splitlines()[0])[:100].strip()
    title = ' '.join(title.split())
    slug = unicodedata.normalize('NFKD', title).encode('ascii', 'ignore').decode().lower()
    slug = re.sub(r'[^a-z0-9]+', '-', slug).strip('-')[:60] or 'catatan'
    now = datetime.now().astimezone()
    path = root / 'inbox_raw' / f'{now:%Y%m%d-%H%M%S}-{slug}-{uuid4().hex[:8]}.md'
    if not path.resolve().is_relative_to(root.resolve()):
        raise ValueError('Inbox berada di luar vault.')
    path.parent.mkdir(parents=True, exist_ok=True)
    content = f'---\ntitle: {json.dumps(title, ensure_ascii=False)}\ntype: capture\ncreated_at: {now.isoformat(timespec="seconds")}\nsource: local-user\n---\n\n{text.rstrip()}\n'
    with path.open('x', encoding='utf-8', newline='\n') as handle:
        handle.write(content)
    # No automatic LLM ingestion or external transfer.
    rel = path.relative_to(root).as_posix()
    try:
        with (root / 'log.md').open('a', encoding='utf-8') as handle:
            handle.write(f'\n| {now:%Y-%m-%d %H:%M} | CAPTURE | `{rel}` | User capture via brain.py |\n')
    except OSError as error:
        print(f'Catatan tersimpan, tetapi audit log gagal ditulis: {error}', file=sys.stderr)
    return path

def safe(text):
    return str(text).replace('|', '/').replace('[', '(').replace(']', ')').replace('\n', ' ')

def link(note):
    return f"[[{note['path'][:-3]}|{safe(note['title'])}]]"

def home(root):
    items, streams, pending, inbox = snapshot(root)
    rows = [MARKER, '# Mulai di sini', '', '> Ringkasan lokal. Jalankan `brain.cmd home` untuk memperbarui. Konten domain private dikecualikan.', '',
            f'Diperbarui: {datetime.now().astimezone():%Y-%m-%d %H:%M %Z}', '',
            f'**{len(streams)} proyek aktif · {len(pending)} tugas terbuka · {len(inbox)} catatan inbox**', '',
            '## Rutinitas 5 menit', '',
            '1. Simpan ide: klik dua kali `brain.cmd`, pilih **Catat ide**.',
            '2. Cari: `brain.cmd search "kata kunci"` (semua kata harus ditemukan).',
            '3. Pilih satu tugas di bawah dan kerjakan dari catatan sumber.',
            '4. Tinjau inbox. Pemrosesan AI melalui skrip ingest lama tetap dijalankan secara terpisah.',
            '5. Perbarui halaman ini: `brain.cmd home`.', '',
            '## Proyek aktif', '', '| Catatan | Tugas terbuka |', '| --- | --- |']
    for note in streams:
        rows.append(f'| {link(note)} | {len(list(tasks(note)))} |')
    if not streams:
        rows.append('| Belum ada catatan dengan `status: active` | 0 |')
    rows += ['', '## Tugas dari proyek aktif', '', '> Urutan mengikuti path sumber; bukan rekomendasi prioritas. Halaman ini ringkasan baca saja: centang tugas di catatan sumber.', '']
    rows += [f'- {safe(task)} — {link(note)} (baris {line})' for note, line, task in pending[:30]] or ['Belum ada tugas terbuka.']
    if len(pending) > 30:
        rows.append(f'\nMenampilkan 30 dari {len(pending)} tugas; lihat catatan sumber untuk sisanya.')
    rows += ['', '## Inbox yang belum diproses', '']
    rows += [f'- {link(n)}' for n in sorted(inbox, key=lambda n: n['mtime'], reverse=True)[:15]] or ['Inbox kosong.']
    if len(inbox) > 15:
        rows.append(f'\nMenampilkan 15 dari {len(inbox)} catatan.')
    rows += ['', '## Catatan terbaru', '']
    rows += [f'- {link(n)}' for n in sorted(items, key=lambda n: n['mtime'], reverse=True)[:8]]
    queue = [n for n in items if n['meta'].get('workflow') == 'two-agent-execution' and n['meta'].get('artifact') == 'brief']
    rows += ['', '## Task eksekusi — dua agen', '',
             'Buat paket: `brain.cmd plan "ide saya"`. Salin prompt 03 dari paket ke Codex untuk menjalankan Agen 1 → Agen 2 → review Tio.',
             'Panduan: [[TASK_EXECUTION|Task eksekusi]]. Paket berikut masih dapat berstatus pending; lihat proposal sumber.', '']
    rows += [f'- {link(n)} — review: {safe(n["meta"].get("review_status", "pending"))}' for n in sorted(queue, key=lambda n: n['mtime'], reverse=True)[:10]] or ['Belum ada paket ide.']
    rows += ['', '## Navigasi & bantuan', '', '- [[index|Indeks pengetahuan]]', '- [[QUICKSTART|Panduan singkat]]',
             '- [[MANUAL|Manual lengkap]]', '- `brain.cmd doctor` — periksa vault dan indeks pencarian lama.', '',
             'Pencarian bawaan membaca Markdown terbaru tanpa API, model, atau indeks. Gunakan `--include-private` hanya pada pencarian/status terminal jika diperlukan.', '']
    target = root / 'HOME.md'
    if target.exists() and not target.read_text(encoding='utf-8').startswith(MARKER):
        raise ValueError('HOME.md sudah berisi catatan pengguna; tidak ditimpa.')
    with tempfile.NamedTemporaryFile(mode='w', encoding='utf-8', dir=root, delete=False, suffix='.tmp') as handle:
        temporary = Path(handle.name)
        handle.write('\n'.join(rows))
    try:
        os.replace(temporary, target)
    finally:
        temporary.unlink(missing_ok=True)
    return target

def doctor(root):
    items, streams, pending, inbox = snapshot(root)
    print(f'Python: {sys.executable}\nVault: {root}')
    print(f'Catatan terlihat: {len(items)} | Aktif: {len(streams)} | Tugas: {len(pending)} | Inbox: {len(inbox)}')
    for folder in FOLDERS:
        print(f'{"OK" if (root / folder).is_dir() else "INFO belum tersedia"}: {folder}/')
    database = root / 'data/vault_search.db'
    indexed = [n for n in items if not n['path'].startswith(('raw/', 'inbox_raw/'))]
    if not database.exists():
        print('INFO indeks hybrid belum tersedia; pencarian brain.cmd tetap berfungsi.')
    else:
        newer = sum(n['mtime'] > database.stat().st_mtime for n in indexed)
        print(f'Indeks hybrid: {newer} catatan lebih baru daripada database (indikator waktu, bukan validasi isi).')
    unknown = [n for n in items if n['path'].startswith('in_motion/') and not n['meta'].get('status')]
    print(f'INFO {len(unknown)} catatan in_motion tanpa status; tidak diasumsikan aktif.')
    if (root / 'package.json').exists() and not (root / 'packages/client/package.json').exists():
        print('INFO workspace Node belum lengkap: packages/client/package.json belum ada. Gunakan alur Markdown/Python.')
    print('Private dikecualikan. Pemeriksaan vault ini tidak menguji kredensial atau koneksi eksternal.')

def show_status(root, include_private=False):
    items, streams, pending, inbox = snapshot(root, include_private)
    print(f'{len(items)} catatan | {len(streams)} proyek aktif | {len(pending)} tugas terbuka | {len(inbox)} inbox')
    for folder, count in sorted(Counter(n['path'].split('/')[0] for n in items).items()):
        print(f'  {folder}: {count}')
    for note in streams:
        print(f'  AKTIF: {note["title"]} ({note["path"]})')

def show_results(results):
    if not results:
        print('Tidak ditemukan. Coba kata kunci lebih singkat; semua kata harus ada dalam catatan.')
    for result in results:
        print(f'\n{result["title"]}\n  {result["path"]}:{result["line"]}\n  {result["excerpt"]}')
